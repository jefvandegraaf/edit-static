#!/usr/bin/env node
// EditStatic command line.
//   editstatic init [--host netlify|cloudflare] [--branch staging]   add EditStatic to the site in this folder
//   editstatic apply [--no-build]                                    apply queued edits (the GitHub Action runs this)
//   editstatic find "<text>" [--page /about]                         show where a text on the page lives in the source
//   editstatic local <folder> [--port 8450] [--commit] [--push]      edit a plain HTML folder on your own computer
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const [cmd, ...args] = process.argv.slice(2);
const opt = (name, fallback = null) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
const cwd = process.cwd();

const HOSTS = {
  netlify: { from: 'dist/netlify/editstatic.js', to: 'netlify/edge-functions/editstatic.js' },
  cloudflare: { from: 'dist/cloudflare/_middleware.js', to: 'functions/_middleware.js' },
};

function detectHost() {
  if (fs.existsSync(path.join(cwd, 'netlify.toml')) || fs.existsSync(path.join(cwd, 'netlify'))) return 'netlify';
  if (fs.existsSync(path.join(cwd, 'wrangler.toml')) || fs.existsSync(path.join(cwd, 'wrangler.json')) || fs.existsSync(path.join(cwd, 'functions'))) return 'cloudflare';
  return null;
}
const ours = (file) => !fs.existsSync(file) || /Generated by EditStatic/.test(fs.readFileSync(file, 'utf8').slice(0, 300));

function init() {
  const host = opt('--host') || detectHost();
  if (!HOSTS[host]) {
    console.error('Which host deploys this site? Run again with --host netlify or --host cloudflare.');
    process.exit(1);
  }
  const branch = opt('--branch', 'staging');
  if (!fs.existsSync(path.join(cwd, '.git'))) console.warn('Note: this folder is not the root of a git repo. Run init in the repo root.');
  const { from, to } = HOSTS[host];
  const dest = path.join(cwd, to);
  if (!ours(dest)) {
    console.error(`${to} already exists and isn't from EditStatic. Move it aside (or merge it by hand), then run init again.`);
    process.exit(1);
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(path.join(ROOT, from), dest);
  console.log(`  wrote ${to}`);
  const wf = path.join(cwd, '.github/workflows/editstatic.yml');
  fs.mkdirSync(path.dirname(wf), { recursive: true });
  fs.writeFileSync(wf, fs.readFileSync(path.join(ROOT, 'templates/editstatic.yml'), 'utf8').replaceAll('__BRANCH__', branch).replaceAll('__VERSION__', 'v' + pkg.version));
  console.log('  wrote .github/workflows/editstatic.yml');
  const cfg = path.join(cwd, 'editstatic.config.json');
  if (!fs.existsSync(cfg)) {
    fs.writeFileSync(cfg, JSON.stringify({ sources: ['.'], ignore: [], build: null }, null, 2) + '\n');
    console.log('  wrote editstatic.config.json');
  }
  const repo = guessRepo() || 'owner/repo';
  const editHost = host === 'netlify' ? `${branch}--<your-site>.netlify.app` : `${branch}.<your-project>.pages.dev`;
  console.log(`
EditStatic is in. Commit these files to the ${branch} branch and push. Then, once:

1. GitHub token: https://github.com/settings/personal-access-tokens/new
   Only select repositories: ${repo.split('/')[1] || 'your repo'}. Permissions: Contents, Read and write.
2. GitHub: ${repo} > Settings > Actions > General > Workflow permissions > Read and write permissions.
3. ${host === 'netlify'
    ? `Netlify: Project configuration > Build & deploy > Continuous deployment > Branches and deploy
   contexts > Branch deploys: add "${branch}". Then Environment variables, with a value for the
   "Branch deploys" context only (and the Functions scope, if your plan shows scopes):`
    : `Cloudflare: Workers & Pages > your project > Settings > Variables and Secrets,
   Preview environment only (not Production):`}
     EDIT_PASSWORD   a long password you choose       (secret)
     GITHUB_TOKEN    the token from step 1             (secret)
     GITHUB_REPO     ${repo}
     GITHUB_BRANCH   ${branch}
     EDIT_HOST       ${editHost}
4. Redeploy ${branch}, open https://${editHost}/?edit and enter the password.
   Check the setup at https://${editHost}/__es/api/health
`);
}

function guessRepo() {
  try {
    const conf = fs.readFileSync(path.join(cwd, '.git/config'), 'utf8');
    const m = /url = .*github\.com[:/]([^/\s]+\/[^/\s]+?)(\.git)?\s*$/m.exec(conf);
    return m ? m[1] : null;
  } catch { return null; }
}

async function apply() {
  const { processQueue } = await import('../packages/sync/src/apply.js');
  await processQueue(cwd, { build: !args.includes('--no-build') });
}

async function find() {
  const text = args.find((a, i) => !a.startsWith('--') && args[i - 1] !== '--page');
  if (!text) { console.error('Usage: editstatic find "<text as it reads on the page>" [--page /about]'); process.exit(1); }
  const { createSync } = await import('../packages/sync/src/index.js');
  const { hits, all, where } = createSync(cwd).locate(text.replace(/&/g, '&amp;').replace(/</g, '&lt;'), opt('--page', '/'));
  if (!all.length) { console.log('Not found as text in any source file (it may be made by code).'); return; }
  console.log(hits.length === 1 ? `Would be saved to ${where(hits[0])}` : `Ambiguous: ${hits.length} equally good places`);
  for (const h of all) console.log(`  ${hits.includes(h) ? '*' : ' '} ${where(h)}${h.whole ? '' : ' (part of a longer text)'}`);
}

const HELP = `EditStatic ${pkg.version}: click-to-edit text for AI-built and static sites.

  editstatic init [--host netlify|cloudflare] [--branch staging]
  editstatic apply [--no-build]
  editstatic find "<text>" [--page /about]
  editstatic local <folder> [--port 8450] [--commit] [--push]

https://github.com/jefvandegraaf/edit-static`;

if (cmd === 'init') init();
else if (cmd === 'apply') await apply();
else if (cmd === 'find') await find();
else if (cmd === 'local') spawn(process.execPath, [path.join(ROOT, 'apps/local/server.js'), ...args], { stdio: 'inherit' }).on('exit', (c) => process.exit(c ?? 0));
else if (cmd === '--version' || cmd === '-v') console.log(pkg.version);
else { console.log(HELP); if (cmd && cmd !== 'help' && cmd !== '--help') process.exit(1); }
