// EditStatic source sync: writes text edits made on a live page back into the files the page is
// built from. Works for plain HTML, Markdown/MDX (YAML or JSON frontmatter), JSON content files and
// JavaScript/TypeScript/JSX (React sites from Lovable, Bolt, v0, Replit, Cursor, Claude Code...).
//
// Each change is { before, after }: the edited element's inner HTML before and after. The text is
// looked up by what a visitor reads (markup, entities and spacing ignored). It is written back only
// when there is exactly one sensible place for it; otherwise the edit is refused with the reason,
// so a rebuild can never silently undo it.
import fs from 'node:fs';
import path from 'node:path';
import { zonesFor, visible, htmlSegments } from './zones.js';
import { findHits, plan, applySplices, lineOf } from './match.js';

export const DEFAULT_IGNORE = ['node_modules', '.git', '.github', '.editstatic', 'dist', 'build', 'out', '.next', '.nuxt', '.output',
  '.svelte-kit', '.astro', '.vercel', '.netlify', '.wrangler', '.cache', 'coverage', 'vendor', 'functions', 'netlify'];
const EXT = /\.(html?|md|mdx|markdown|json|ya?ml|(c|m)?(j|t)sx?)$/i;
const SKIP_FILE = /^(package(-lock)?\.json|pnpm-lock\.yaml|yarn\.lock|bun\.lockb?|(ts|js)config.*\.json|components\.json|deno\.jsonc?|vercel\.json|netlify\.toml|wrangler\.(toml|json)|editstatic\.config\.json|.*\.config\.(c|m)?(j|t)s|.*\.d\.ts|.*\.min\.js|.*\.(test|spec)\.(j|t)sx?|pnpm-workspace\.yaml|docker-compose\.ya?ml|\.?[a-z-]*rc\.(json|ya?ml))$/i;
const MAX_FILE = 512 * 1024;

export function loadConfig(root) {
  const f = path.join(root, 'editstatic.config.json');
  const cfg = fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : {};
  return { sources: ['.'], ignore: [], build: null, ...cfg };
}

export function listSources(root, cfg = loadConfig(root)) {
  const ignore = new Set([...DEFAULT_IGNORE, ...cfg.ignore]);
  const out = [];
  const walkDir = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      const rel = path.relative(root, full).split(path.sep).join('/');
      if (ignore.has(e.name) || ignore.has(rel) || e.name.startsWith('.')) continue;
      if (e.isDirectory()) walkDir(full);
      else if (EXT.test(e.name) && !SKIP_FILE.test(e.name) && fs.statSync(full).size <= MAX_FILE) out.push(full);
    }
  };
  for (const s of cfg.sources) {
    const full = path.resolve(root, s);
    if (!fs.existsSync(full)) continue;
    if (fs.statSync(full).isDirectory()) walkDir(full); else out.push(full);
  }
  return [...new Set(out)];
}

// files that probably belong to this page: /about/ -> about/index.html, src/pages/About.tsx, content/about.md
function ownFile(rel, page) {
  const parts = page.replace(/index\.html?$/, '').split('/').filter(Boolean);
  const slug = (parts[parts.length - 1] || '').toLowerCase();
  const p = rel.toLowerCase().replace(/\.[^./]+$/, '');
  const base = p.split('/').pop(), dir = p.split('/').slice(-2, -1)[0] || '';
  if (!slug) return ['index', 'home', 'homepage'].includes(base) && (!dir || /^(src|pages|app|routes|content|public|views)$/.test(dir));
  return base === slug || base === slug + 'page' || ((base === 'index' || base === 'page' || base === '+page') && dir === slug);
}

export function createSync(root, cfg = loadConfig(root)) {
  const cache = new Map();
  const zones = (file) => {
    const text = fs.readFileSync(file, 'utf8');
    const hit = cache.get(file);
    if (hit && hit.text === text) return hit;
    if (/Generated by EditStatic/.test(text.slice(0, 300))) { cache.set(file, { text, zones: [] }); return cache.get(file); }
    const entry = { text, zones: zonesFor(file, text) };
    cache.set(file, entry);
    return entry;
  };
  const rel = (f) => path.relative(root, f).split(path.sep).join('/');

  // where a text is: every hit, best first, without writing anything
  function locate(before, page = '/') {
    const needle = visible(before);
    let hits = [];
    for (const file of listSources(root, cfg)) {
      const { zones: zs } = zones(file);
      for (const z of zs) hits.push(...findHits(z, needle));
    }
    // the same source characters can be reached through two zones (a <span> unit inside an <h1> unit): keep the whole one
    hits.sort((x, y) => Number(y.whole) - Number(x.whole));
    const seen = new Set();
    hits = hits.filter((h) => {
      const k = `${h.zone.file}:${h.zone.map[h.a][0]}:${h.zone.map[h.b - 1][1]}`;
      if (seen.has(k)) return false;
      seen.add(k);
      return true;
    });
    const all = hits;
    // a match that is the whole element beats the same words inside a longer one,
    // this page's files beat shared ones, and page text beats frontmatter (titles, meta descriptions)
    if (hits.length > 1 && hits.some((h) => h.whole)) hits = hits.filter((h) => h.whole);
    if (hits.length > 1 && hits.some((h) => ownFile(rel(h.zone.file), page))) hits = hits.filter((h) => ownFile(rel(h.zone.file), page));
    if (hits.length > 1 && hits.some((h) => !h.zone.meta)) hits = hits.filter((h) => !h.zone.meta);
    const where = (h) => `${rel(h.zone.file)}:${lineOf(cache.get(h.zone.file).text, h.zone.map[h.a][0])}`;
    return { needle, hits, all, where };
  }

  async function sync({ page = '/', changes }) {
    const results = [];
    for (const { before, after } of changes) {
      try { results.push(one(before, after, page)); }
      catch (err) { results.push({ ok: false, error: 'Couldn\'t apply this edit: ' + err.message }); }
    }
    return results;
  }

  function one(before, after, page) {
    if (visible(before).replace(/\s/g, '').length < 2) return { ok: false, error: 'That text is too short to find in the source files' };
    const same = htmlSegments(before).join('|').replace(/\s+/g, ' ') === htmlSegments(after).join('|').replace(/\s+/g, ' ');
    if (same && before.replace(/\s+/g, ' ') === after.replace(/\s+/g, ' ')) return { ok: true, file: '(no change)' };
    const { hits, where } = locate(before, page);
    if (!hits.length) return { ok: false, error: 'This text is made by the site\'s code, not stored as text in a source file. Change it in the code.' };
    if (hits.length > 1) {
      const list = hits.slice(0, 4).map(where).join(', ') + (hits.length > 4 ? ', ...' : '');
      return { ok: false, error: `This text is in ${hits.length} places (${list}). Change it there so the right one is edited.` };
    }
    const hit = hits[0];
    const file = hit.zone.file;
    const text = cache.get(file).text;
    const p = plan(hit, text, before, after, rel(file));
    if (p.error) return { ok: false, error: p.error };
    if (p.splices.length) fs.writeFileSync(file, applySplices(text, p.splices));
    return { ok: true, file: rel(file), line: lineOf(text, hit.zone.map[hit.a][0]) };
  }

  return { sync, locate };
}

// The --sync module interface of the local server: default export (root, page, changes) => results
export default async function sync({ root, page, changes }) {
  return createSync(root).sync({ page, changes });
}
