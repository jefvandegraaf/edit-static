// Bundles EditStatic web into a static site repo:
//   <site>/functions/_middleware.js       Cloudflare Pages middleware (login, save, status)
//   <site>/assets/editstatic/web.js       browser loader (tags regions, opens the editor)
//   <site>/assets/editstatic/editor.js    the in-page editor
//   node apps/web/build.mjs <site-folder>
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const site = process.argv[2];
if (!site) { console.error('Usage: node apps/web/build.mjs <site-folder>'); process.exit(1); }
const SITE = path.resolve(site);
const banner = { js: '/* Generated by EditStatic (apps/web/build.mjs). Edit the source in the EditStatic repo, not this file. */' };

await build({ entryPoints: [path.join(HERE, 'middleware.js')], outfile: path.join(SITE, 'functions/_middleware.js'), bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', banner, logLevel: 'warning' });
await build({ entryPoints: [path.join(HERE, 'client.js')], outfile: path.join(SITE, 'assets/editstatic/web.js'), bundle: true, format: 'iife', platform: 'browser', target: 'es2020', minify: true, mainFields: ['module', 'main'], banner, logLevel: 'warning' });
fs.copyFileSync(path.join(HERE, '../../packages/editor/editor.js'), path.join(SITE, 'assets/editstatic/editor.js'));
for (const f of ['functions/_middleware.js', 'assets/editstatic/web.js', 'assets/editstatic/editor.js']) console.log('  wrote', f, Math.round(fs.statSync(path.join(SITE, f)).size / 1024) + ' KB');
