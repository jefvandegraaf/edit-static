// Builds the one file each host needs, with the browser loader and the editor inlined:
//   dist/cloudflare/_middleware.js   -> <site>/functions/_middleware.js
//   dist/netlify/editstatic.js       -> <site>/netlify/edge-functions/editstatic.js
// `editstatic init` copies the right one into a site. Run after changing anything in apps/web or
// packages/editor: npm run build
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const banner = `/* Generated by EditStatic ${pkg.version} (https://github.com/jefvandegraaf/edit-static). Don't edit: run \`npx github:jefvandegraaf/edit-static init\` again to update. */`;

const client = await build({ entryPoints: [path.join(HERE, 'client.js')], bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2020', minify: true, logLevel: 'warning' });
const editor = await build({ entryPoints: [path.join(ROOT, 'packages/editor/editor.js')], bundle: false, write: false, minify: true, target: 'es2020', logLevel: 'warning' });
const define = {
  __ES_CLIENT__: JSON.stringify(client.outputFiles[0].text),
  __ES_EDITOR__: JSON.stringify(editor.outputFiles[0].text),
};
const targets = [['cloudflare.js', 'dist/cloudflare/_middleware.js'], ['netlify.js', 'dist/netlify/editstatic.js']];
for (const [entry, out] of targets) {
  await build({ entryPoints: [path.join(HERE, entry)], outfile: path.join(ROOT, out), bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', define, banner: { js: banner }, logLevel: 'warning' });
  if (entry === 'netlify.js') {
    // Netlify reads the route from a literal `export const config`, so keep it in that form
    const file = path.join(ROOT, out);
    const js = fs.readFileSync(file, 'utf8').replace(/^var config = /m, 'export const config = ').replace(/^\s*config,\n/m, '');
    if (!/^export const config = /m.test(js)) throw new Error('netlify config export not found');
    fs.writeFileSync(file, js);
  }
  console.log('  wrote', out, Math.round(fs.statSync(path.join(ROOT, out)).size / 1024) + ' KB');
}
